export function newsFor(s: GameState): string {
  if (s.debt > 500000)
    return "Банки назвали ваших потомков перспективным рынком.";
  if (s.properties.includes("shawarma"))
    return "В районе исчезли голуби. Шаурмичные отрицают связь.";
  if (s.job === "politician")
    return "Укропия объявила понедельник иностранным агентом календаря.";
  return headlines[(s.turn + s.seed) % headlines.length];
}
export function rumorFor(s: GameState): string {
  if (s.flags.stool)
    return "Сосед помнит табуретку. Сосед готовит презентацию.";
  if (s.stats.reputation > 75)
    return "На районе говорят, что у вас есть ответы. Не портите легенду.";
  if (s.relationships.some((r) => r.role === "супруг"))
    return "Семейный чат уже знает, куда вы потратили деньги.";
  return [
    "Говорят, в соседнем подъезде человек выплатил ипотеку. Очевидцы ненадёжны.",
    "Бабушка уверяет, что работа лечит всё. Клинические испытания продолжаются.",
    "Гаражный кооператив снова обсуждает выход из состава двора.",
    "Кто-то видел счастливого бухгалтера. Вероятно, монтаж.",
  ][s.turn % 4];
}
