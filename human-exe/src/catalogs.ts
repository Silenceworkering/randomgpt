export function endingFor(s: GameState): string {
  let i =
    s.money >= 1e9
      ? 0
      : (s.flags.pigeon || 0) >= 3 || s.flags.ending_pigeon_0 === 1
        ? 1
        : s.job === "politician" && s.stats.reputation > 65
          ? 2
          : s.stats.reputation >= 85
            ? 3
            : s.relationships.some((r) => r.role !== "семья" && r.bond >= 80) &&
                s.stats.stress < 45
              ? 4
              : s.debt > s.money + 1e6
                ? 5
                : s.stats.health < 10 && s.money < 1000
                  ? 6
                  : s.job === "criminal"
                    ? 7
                    : s.job === "blogger"
                      ? 8
                      : s.stats.intellect >= 90
                        ? 9
                        : s.properties.includes("shawarma")
                          ? 10
                          : s.properties.includes("factory")
                            ? 11
                            : s.properties.length >= 4
                              ? 12
                              : s.relationships.some((r) => r.role === "супруг")
                                ? 13
                                : (s.flags.work || 0) >= 20
                                  ? 14
                                  : (s.flags.rest || 0) >= 15
                                    ? 15
                                    : s.debt > 0
                                      ? 16
                                      : s.seen.length >= 60
                                        ? 17
                                        : s.age < 25
                                          ? 19
                                          : 18;
  return ENDINGS[i].id;
}
